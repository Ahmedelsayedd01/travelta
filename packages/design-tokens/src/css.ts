import { colorRoles, colors, type ThemeName } from './semantic';
import { fontSize, radii, shadows } from './scales';

const shadowKeys = Object.keys(shadows.light) as (keyof (typeof shadows)['light'])[];

function themeBlock(theme: ThemeName, indent = '  '): string {
  return [
    ...colorRoles.map((role) => `${indent}--tv-${role}: ${colors[theme][role]};`),
    ...shadowKeys.map((k) => `${indent}--tv-shadow-${k}: ${shadows[theme][k]};`),
  ].join('\n');
}

const HEADER = '/* GENERATED by @travelta/design-tokens (pnpm --filter @travelta/design-tokens generate). Do not edit. */';

/** Theme values as `--tv-*` custom properties: light by default, dark via OS preference or `data-theme="dark"`. */
export function generateTokensCss(): string {
  return `${HEADER}
:root {
${themeBlock('light')}
  color-scheme: light;
}

@media (prefers-color-scheme: dark) {
  :root:not([data-theme='light']) {
${themeBlock('dark', '    ')}
    color-scheme: dark;
  }
}

:root[data-theme='dark'] {
${themeBlock('dark')}
  color-scheme: dark;
}
`;
}

/** Tailwind v4 `@theme` mapping: utilities such as `bg-surface`, `text-fg-muted`, `shadow-md`, `rounded-lg`. */
export function generateThemeCss(): string {
  const colorsMap = colorRoles.map((role) => `  --color-${role}: var(--tv-${role});`).join('\n');
  const shadowMap = shadowKeys.map((k) => `  --shadow-${k}: var(--tv-shadow-${k});`).join('\n');
  const radius = Object.entries(radii)
    .map(([k, v]) => `  --radius-${k}: ${v === 9999 ? '9999px' : `${v / 16}rem`};`)
    .join('\n');
  const type = Object.entries(fontSize)
    .map(([k, v]) => `  --text-${k}: ${v.size / 16}rem;\n  --text-${k}--line-height: ${v.line / 16}rem;`)
    .join('\n');
  return `${HEADER}
@theme inline {
${colorsMap}
${shadowMap}
${radius}
${type}
}
`;
}
